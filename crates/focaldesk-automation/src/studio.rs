//! Versioned visual workflows compiled to the existing automation Lua API.
use crate::{config::AutomationEntry, schedule::Schedule};
use serde::{Deserialize, Serialize};
use std::collections::{BTreeMap, BTreeSet};
use std::path::Path;

#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct Workflow {
    pub version: u32,
    pub id: String,
    pub name: String,
    pub nodes: Vec<Node>,
    pub edges: Vec<Edge>,
}

#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct Node {
    pub id: String,
    pub position: Position,
    pub data: Block,
}

#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct Position {
    pub x: f64,
    pub y: f64,
}

#[derive(Debug, Clone, Serialize, Deserialize)]
#[serde(tag = "kind", rename_all = "snake_case")]
pub enum Block {
    Schedule { schedule: String },
    Condition { hour: u8 },
    Notify { title: String, body: String },
    Log { message: String },
    Volume { level: u8 },
    Wifi { enabled: bool },
    Bluetooth { enabled: bool },
    // Persist design intent, but never silently compile unsupported decisions.
    AiDecision { prompt: String },
    Webhook { path: String },
}

#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct Edge {
    pub id: String,
    pub source: String,
    pub target: String,
    #[serde(default, rename = "sourceHandle")]
    pub source_handle: Option<String>,
}

pub fn valid_id(id: &str) -> bool {
    !id.is_empty()
        && id.len() <= 80
        && id
            .bytes()
            .all(|b| b.is_ascii_alphanumeric() || b == b'-' || b == b'_')
}

/// Restrict v1 graphs to rooted trees: each step executes at most once per run.
/// There are no joins, cycles, implicit disconnected actions, or raw Lua fields.
pub fn compile(flow: &Workflow) -> Result<(String, String), String> {
    if flow.version != 1 || !valid_id(&flow.id) {
        return Err("Unsupported workflow version or invalid workflow ID".into());
    }
    if flow.name.trim().is_empty() || flow.name.len() > 160 {
        return Err("Workflow name must contain 1–160 characters".into());
    }
    if flow.nodes.is_empty() || flow.nodes.len() > 100 || flow.edges.len() > 200 {
        return Err("Use 1–100 blocks and at most 200 connections".into());
    }
    let nodes: BTreeMap<_, _> = flow.nodes.iter().map(|n| (n.id.as_str(), n)).collect();
    if nodes.len() != flow.nodes.len() || flow.nodes.iter().any(|n| !valid_id(&n.id)) {
        return Err("Block IDs must be unique and valid".into());
    }
    let roots: Vec<_> = flow
        .nodes
        .iter()
        .filter(|n| matches!(n.data, Block::Schedule { .. }))
        .collect();
    if roots.len() != 1 {
        return Err("Connect exactly one schedule trigger".into());
    }
    let root = roots[0];
    let Block::Schedule { schedule } = &root.data else {
        unreachable!()
    };
    Schedule::parse(schedule)?;
    let mut incoming = BTreeSet::new();
    let mut edge_ids = BTreeSet::new();
    for e in &flow.edges {
        if !edge_ids.insert(&e.id) {
            return Err("Connection IDs must be unique".into());
        }
        let Some(source) = nodes.get(e.source.as_str()) else {
            return Err("Connection source does not exist".into());
        };
        if !nodes.contains_key(e.target.as_str()) {
            return Err("Connection target does not exist".into());
        }
        if e.target == root.id || !incoming.insert(&e.target) {
            return Err(
                "A block can have only one incoming connection; triggers cannot have one".into(),
            );
        }
        if matches!(source.data, Block::Condition { .. }) {
            if !matches!(e.source_handle.as_deref(), Some("yes" | "no")) {
                return Err("Condition connections must use the Yes or No output".into());
            }
        } else if e.source_handle.is_some() {
            return Err("Only conditions have named outputs".into());
        }
    }
    let mut visited = BTreeSet::new();
    let mut lua = String::from("-- Generated by FocalDesk Automation Studio.\n");
    emit(root.id.as_str(), flow, &nodes, &mut visited, &mut lua, 0)?;
    if visited.len() != nodes.len() {
        return Err(
            "Every block must be connected to the schedule; cycles are not supported".into(),
        );
    }
    if nodes.len() < 2 {
        return Err("Add at least one action after the trigger".into());
    }
    Ok((schedule.clone(), lua))
}

fn quote(s: &str) -> Result<String, String> {
    if s.len() > 16_384 {
        return Err("Block text exceeds 16 KiB".into());
    }
    // Decimal byte escapes are Lua-safe for quotes, newlines, NUL and UTF-8.
    let mut out = String::from("\"");
    for b in s.bytes() {
        out.push_str(&format!("\\{b:03}"));
    }
    out.push('"');
    Ok(out)
}

fn emit<'a>(
    id: &'a str,
    flow: &'a Workflow,
    nodes: &BTreeMap<&'a str, &'a Node>,
    visited: &mut BTreeSet<&'a str>,
    lua: &mut String,
    depth: usize,
) -> Result<(), String> {
    if !visited.insert(id) {
        return Err("Cycles are not supported".into());
    }
    let node = nodes[id];
    let indent = "  ".repeat(depth);
    let statement = match &node.data {
        Block::Schedule { .. } => String::new(),
        Block::Condition { hour } => {
            if *hour > 23 {
                return Err("Condition hour must be between 0 and 23".into());
            }
            lua.push_str(&format!(
                "{indent}if tonumber(os.date('%H')) >= {hour} then\n"
            ));
            for branch in ["yes", "no"] {
                if branch == "no" {
                    lua.push_str(&format!("{indent}else\n"));
                }
                for e in flow
                    .edges
                    .iter()
                    .filter(|e| e.source == id && e.source_handle.as_deref() == Some(branch))
                {
                    emit(&e.target, flow, nodes, visited, lua, depth + 1)?;
                }
            }
            lua.push_str(&format!("{indent}end\n"));
            return Ok(());
        }
        Block::Notify { title, body } => {
            if title.trim().is_empty() {
                return Err("Notification title is required".into());
            }
            format!("notify({}, {})", quote(title)?, quote(body)?)
        }
        Block::Log { message } => format!("log({})", quote(message)?),
        Block::Volume { level } => {
            if *level > 100 {
                return Err("Volume must be between 0 and 100".into());
            }
            format!("volume({})", f64::from(*level) / 100.0)
        }
        Block::Wifi { enabled } => format!("wifi_power({enabled})"),
        Block::Bluetooth { enabled } => format!("bluetooth_power({enabled})"),
        Block::AiDecision { .. } => {
            return Err(
                "AI decisions are draft-only: the automation engine has no AI decision API yet"
                    .into(),
            );
        }
        Block::Webhook { .. } => {
            return Err(
                "Webhook triggers are draft-only: the engine currently supports schedules".into(),
            );
        }
    };
    if !statement.is_empty() {
        lua.push_str(&format!("{indent}{statement}\n"));
    }
    for e in flow.edges.iter().filter(|e| e.source == id) {
        emit(&e.target, flow, nodes, visited, lua, depth)?;
    }
    Ok(())
}

/// Files live below the automation root. Never rewrite hand-authored config.
pub fn save_draft(root: &Path, flow: &Workflow) -> Result<(), String> {
    if flow.version != 1 || !valid_id(&flow.id) || flow.nodes.len() > 100 || flow.edges.len() > 200
    {
        return Err("Invalid draft ID, version, or graph size".into());
    }
    let data = serde_json::to_vec_pretty(flow).map_err(|e| e.to_string())?;
    if data.len() > 2_000_000 {
        return Err("Draft exceeds 2 MB".into());
    }
    atomic_write(
        &root.join("drafts").join(format!("{}.json", flow.id)),
        &data,
    )
}

pub fn publish(root: &Path, flow: &Workflow) -> Result<(), String> {
    let (schedule, lua) = compile(flow)?;
    save_draft(root, flow)?;
    // Unique, immutable scripts mean the manifest rename is the commit point.
    let revision = std::time::SystemTime::now()
        .duration_since(std::time::UNIX_EPOCH)
        .map_err(|e| e.to_string())?
        .as_nanos();
    let script_path = root
        .join("scripts")
        .join(format!("{}-{revision}.lua", flow.id));
    atomic_write(&script_path, lua.as_bytes())?;
    let entry = AutomationEntry {
        name: format!("studio:{}", flow.id),
        script: script_path.to_str().ok_or("Non-UTF-8 script path")?.into(),
        schedule,
        enabled: true,
    };
    let text = toml::to_string(&entry).map_err(|e| e.to_string())?;
    atomic_write(
        &root.join("published").join(format!("{}.toml", flow.id)),
        text.as_bytes(),
    )
}

fn atomic_write(path: &Path, data: &[u8]) -> Result<(), String> {
    use std::io::Write;
    std::fs::create_dir_all(path.parent().ok_or("Missing parent directory")?)
        .map_err(|e| e.to_string())?;
    let temp = path.with_extension(format!("{}.tmp", std::process::id()));
    let mut file = std::fs::OpenOptions::new()
        .write(true)
        .create_new(true)
        .open(&temp)
        .map_err(|e| e.to_string())?;
    let result = (|| {
        file.write_all(data).map_err(|e| e.to_string())?;
        file.sync_all().map_err(|e| e.to_string())?;
        std::fs::rename(&temp, path).map_err(|e| e.to_string())
    })();
    if result.is_err() {
        let _ = std::fs::remove_file(temp);
    }
    result
}

#[cfg(test)]
mod tests {
    use super::*;
    fn flow() -> Workflow {
        serde_json::from_str(r#"{"version":1,"id":"test","name":"Test","nodes":[{"id":"s","position":{"x":0,"y":0},"data":{"kind":"schedule","schedule":"daily 09:00"}},{"id":"l","position":{"x":0,"y":100},"data":{"kind":"log","message":"Hello"}}],"edges":[{"id":"e","source":"s","target":"l"}]}"#).unwrap()
    }
    #[test]
    fn compiles_and_executes_quoted_text_without_injection() {
        let mut f = flow();
        f.nodes[1].data = Block::Log {
            message: "\" ); error('injected') --\n\0🦊".into(),
        };
        let (_, lua) = compile(&f).unwrap();
        let vm = mlua::Lua::new();
        vm.globals()
            .set(
                "log",
                vm.create_function(|_, s: String| {
                    assert!(s.contains("🦊"));
                    Ok(())
                })
                .unwrap(),
            )
            .unwrap();
        vm.load(lua).exec().unwrap();
    }
    #[test]
    fn rejects_disconnected_cycles_and_invalid_edges() {
        let mut f = flow();
        f.edges[0].target = "s".into();
        assert!(compile(&f).is_err());
        f.edges.clear();
        assert!(compile(&f).is_err());
        f.edges.push(Edge {
            id: "e".into(),
            source: "s".into(),
            target: "missing".into(),
            source_handle: None,
        });
        assert!(compile(&f).is_err());
    }
    #[test]
    fn conditions_compile_both_branches_and_reject_unknown_handles() {
        let mut f = flow();
        f.nodes.push(Node {
            id: "c".into(),
            position: Position { x: 0.0, y: 0.0 },
            data: Block::Condition { hour: 0 },
        });
        f.edges[0].target = "c".into();
        f.edges.push(Edge {
            id: "b".into(),
            source: "c".into(),
            target: "l".into(),
            source_handle: Some("yes".into()),
        });
        let (_, lua) = compile(&f).unwrap();
        assert!(lua.contains("else\nend"));
        f.edges[1].source_handle = Some("typo".into());
        assert!(compile(&f).is_err());
    }
    #[test]
    fn unsupported_ai_cannot_be_published() {
        let mut f = flow();
        f.nodes[1].data = Block::AiDecision {
            prompt: "Decide".into(),
        };
        assert!(compile(&f).unwrap_err().contains("draft-only"));
        f.id = "../escape".into();
        assert!(compile(&f).is_err());
    }
    #[test]
    fn publishes_manifest_without_touching_existing_config() {
        let root = std::env::temp_dir().join(format!(
            "studio-test-{}-{}",
            std::process::id(),
            crate::runner::now_unix()
        ));
        std::fs::create_dir_all(&root).unwrap();
        std::fs::write(root.join("automations.toml"), "original").unwrap();
        publish(&root, &flow()).unwrap();
        let entry: AutomationEntry =
            toml::from_str(&std::fs::read_to_string(root.join("published/test.toml")).unwrap())
                .unwrap();
        assert_eq!(entry.name, "studio:test");
        assert!(
            std::fs::read_to_string(entry.script)
                .unwrap()
                .contains("log(")
        );
        assert_eq!(
            std::fs::read_to_string(root.join("automations.toml")).unwrap(),
            "original"
        );
        std::fs::remove_dir_all(root).unwrap();
    }
}
