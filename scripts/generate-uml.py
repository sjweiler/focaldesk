#!/usr/bin/env python3
"""Generate declared workspace dependency UML; optionally render local PlantUML.

No Rust source parsing or network access. Runtime diagrams are reviewed sources
in docs/uml; Cargo metadata supplies only declared normal workspace dependencies.
"""

from __future__ import annotations

import argparse
import json
import os
from pathlib import Path
import shutil
import subprocess
import sys
import unittest
import xml.etree.ElementTree as ET

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "docs/uml"
RENDERING = {
    "focaldesk-desktop", "focaldesk-engine", "focaldesk-render",
    "focaldesk-input", "focaldesk-shortcuts", "focaldesk-types", "focaldesk-ui",
}


def model(metadata: dict, root: Path) -> dict:
    members = set(metadata["workspace_members"])
    packages = sorted(
        (p for p in metadata["packages"] if p["id"] in members),
        key=lambda p: p["name"],
    )
    directories = {str(Path(p["manifest_path"]).resolve().parent): p["name"] for p in packages}
    nodes, edges = [], []
    for package in packages:
        manifest = Path(package["manifest_path"]).resolve().relative_to(root.resolve()).as_posix()
        nodes.append({"name": package["name"], "manifest": manifest, "group": manifest.split("/")[0]})
        for dep in package["dependencies"]:
            # --no-deps describes declarations, not the feature-resolved graph.
            # Resolve local paths so aliases cannot accidentally create nodes.
            if dep["kind"] is not None or not dep.get("path"):
                continue
            target = directories.get(str(Path(dep["path"]).resolve()))
            if target is not None:
                edges.append({
                    "from": package["name"], "to": target,
                    "optional": dep["optional"], "target": dep.get("target"),
                    "alias": dep.get("rename"),
                })
    edges.sort(key=lambda edge: json.dumps(edge, sort_keys=True))
    return {"schema_version": 1, "scope": "declared normal workspace dependencies",
            "nodes": nodes, "edges": edges}


def quoted(text: str) -> str:
    return json.dumps(text, ensure_ascii=False)


def diagram(graph: dict, title: str, selected: set[str] | None = None) -> str:
    nodes = [node for node in graph["nodes"] if selected is None or node["name"] in selected]
    aliases = {node["name"]: f"n{i}" for i, node in enumerate(nodes)}
    lines = ["@startuml", "' Generated by scripts/generate-uml.py; do not edit.",
             "!include style.puml", "left to right direction", f"title {title}"]
    for group in sorted({node["group"] for node in nodes}):
        lines.append(f"package {quoted(group)} {{")
        for node in nodes:
            if node["group"] == group:
                lines.append(f'  component {quoted(node["name"])} as {aliases[node["name"]]}')
        lines.append("}")
    # Consolidate target-specific declarations into one labelled dependency.
    grouped: dict[tuple[str, str], list[dict]] = {}
    for edge in graph["edges"]:
        if edge["from"] in aliases and edge["to"] in aliases:
            grouped.setdefault((edge["from"], edge["to"]), []).append(edge)
    for (source, target), edges in sorted(grouped.items()):
        optional = all(edge["optional"] for edge in edges)
        labels = set()
        for edge in edges:
            detail = []
            if edge["optional"]:
                detail.append("optional")
            if edge["target"]:
                detail.append(edge["target"])
            if edge["alias"]:
                detail.append("as " + edge["alias"])
            if detail:
                labels.add(", ".join(detail))
        label = " : " + quoted("; ".join(sorted(labels))) if labels else ""
        arrow = "..>" if optional else "-->"
        lines.append(f"{aliases[source]} {arrow} {aliases[target]}{label}")
    lines.extend(["legend bottom", "Arrows: dependent -> dependency (declarations, not IPC).",
                  "Dotted: optional in every declaration. Target conditions are labels.",
                  "Build/dev dependencies and non-workspace packages are omitted.",
                  "endlegend", "@enduml", ""])
    return "\n".join(lines)


def outputs(graph: dict) -> dict[str, str]:
    return {
        "workspace-dependencies.json": json.dumps(graph, indent=2, sort_keys=True) + "\n",
        "workspace-dependencies.puml": diagram(graph, "FocalDesk workspace dependencies"),
        "rendering-components.puml": diagram(graph, "Rendering: selected workspace dependencies", RENDERING),
    }


def render(jar: Path | None) -> None:
    if jar:
        if not jar.is_file():
            raise ValueError(f"PlantUML JAR not found: {jar}")
        command = ["java", "-Djava.awt.headless=true", "-jar", str(jar.resolve())]
    elif shutil.which("plantuml"):
        command = ["plantuml"]
    else:
        raise ValueError("Install PlantUML or pass --plantuml-jar /path/to/plantuml.jar")
    sources = sorted(path for path in OUT.glob("*.puml") if path.name != "style.puml")
    # Smetana in style.puml provides local layout without Graphviz or a server.
    subprocess.run(command + ["-charset", "UTF-8", "-failfast2", "-tsvg", "-nometadata"]
                   + [str(path) for path in sources], check=True, cwd=ROOT)
    for source in sources:
        svg = source.with_suffix(".svg")
        document = ET.parse(svg).getroot()
        if document.tag != "{http://www.w3.org/2000/svg}svg":
            raise ValueError(f"Invalid SVG: {svg}")
    print(f"Rendered {len(sources)} SVG diagrams locally.")


class ModelTests(unittest.TestCase):
    def test_workspace_paths_aliases_and_dependency_kinds(self):
        def package(name, deps):
            return {"id": name, "name": name, "manifest_path": f"/repo/crates/{name}/Cargo.toml",
                    "dependencies": deps}
        def dep(path, **extra):
            return {"path": path, "kind": None, "optional": False, **extra}
        metadata = {"workspace_members": ["a", "b"], "packages": [
            package("b", []), package("a", [
                dep("/repo/crates/b", optional=True, rename="renamed", target="cfg(unix)"),
                dep("/repo/crates/b", kind="dev"), dep("/repo/crates/b", kind="build"),
                dep("/external/other"), dep(None),
            ]), package("external", []),
        ]}
        graph = model(metadata, Path("/repo"))
        self.assertEqual([n["name"] for n in graph["nodes"]], ["a", "b"])
        self.assertEqual(graph["edges"], [{"from": "a", "to": "b", "optional": True,
                                          "alias": "renamed", "target": "cfg(unix)"}])
        source = diagram(graph, "test")
        self.assertIn("n0 ..> n1", source)
        self.assertIn("as renamed", source)
        self.assertNotIn("n0 ..> n1", diagram(graph, "subset", {"a"}))
        self.assertEqual(model({**metadata, "packages": list(reversed(metadata["packages"]))},
                               Path("/repo")), graph)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Fail if generated sources/JSON are stale")
    parser.add_argument("--render", action="store_true", help="Render all diagram sources locally to SVG")
    parser.add_argument("--plantuml-jar", type=Path, default=os.environ.get("PLANTUML_JAR"))
    parser.add_argument("--self-test", action="store_true", help="Run generator fixture tests only")
    args = parser.parse_args()
    if args.self_test:
        return 0 if unittest.TextTestRunner().run(unittest.defaultTestLoader.loadTestsFromTestCase(ModelTests)).wasSuccessful() else 1
    metadata = json.loads(subprocess.check_output(
        ["cargo", "metadata", "--format-version", "1", "--no-deps", "--offline", "--locked"],
        cwd=ROOT, text=True,
    ))
    graph = model(metadata, ROOT)
    OUT.mkdir(parents=True, exist_ok=True)
    stale = []
    for name, content in outputs(graph).items():
        path = OUT / name
        if args.check:
            if not path.is_file() or path.read_text() != content:
                stale.append(name)
        else:
            path.write_text(content)
    if stale:
        print("Stale UML artifacts: " + ", ".join(stale), file=sys.stderr)
        return 1
    print(f"{'Checked' if args.check else 'Generated'} {len(graph['nodes'])} workspace packages "
          f"and {len(graph['edges'])} dependency declarations.")
    if args.render:
        render(args.plantuml_jar)
    return 0


if __name__ == "__main__":
    try:
        raise SystemExit(main())
    except (ValueError, OSError, subprocess.CalledProcessError, ET.ParseError) as error:
        print(f"UML generation failed: {error}", file=sys.stderr)
        raise SystemExit(1)
